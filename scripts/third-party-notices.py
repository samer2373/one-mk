def metadata():
    command = ["cargo", "metadata", "--locked", "--format-version", "1"]
    result = subprocess.run(command, cwd=ROOT, capture_output=True, text=True)
    if result.returncode != 0:
        sys.exit(f"third-party-notices: `{' '.join(command)}` failed:\n{result.stderr}")
    return json.loads(result.stdout)


def shipped_packages(data):
    """Every package linked into a shipped program: normal dependencies only
    (no dev- or build-dependencies), for every target platform."""
    by_id = {package["id"]: package for package in data["packages"]}
    nodes = {node["id"]: node for node in data["resolve"]["nodes"]}
    members = set(data["workspace_members"])
    roots = [package_id for package_id in members if by_id[package_id]["name"] in SHIPPED]
    missing = set(SHIPPED) - {by_id[package_id]["name"] for package_id in roots}
    if missing:
        sys.exit(f"third-party-notices: shipped packages not in the workspace: {', '.join(sorted(missing))}")
    seen, stack = set(), list(roots)
    while stack:
        package_id = stack.pop()
        if package_id in seen:
            continue
        seen.add(package_id)
        for dep in nodes[package_id]["deps"]:
            if any(kind["kind"] is None for kind in dep["dep_kinds"]):
                stack.append(dep["pkg"])
    return sorted((by_id[package_id] for package_id in seen if package_id not in members),
                  key=lambda package: (package["name"], semver_key(package["version"])))


def semver_key(version):
    core = version.split("+")[0].split("-")[0]
    return tuple(int(part) if part.isdigit() else 0 for part in core.split("."))


def normalise(text):
    lines = [line.rstrip() for line in text.replace("\r\n", "\n").replace("\r", "\n").split("\n")]
    while lines and not lines[0]:
        lines.pop(0)
    while lines and not lines[-1]:
        lines.pop()
    return "\n".join(lines)


def licence_files(package):
    """The licence, copying and notice files at the top of a crate's source."""
    folder = os.path.dirname(package["manifest_path"])
    found = []
    for name in sorted(os.listdir(folder)):
        path = os.path.join(folder, name)
        if not os.path.isfile(path) or not LICENCE_FILE.match(name) or os.path.splitext(name)[1].lower() in CODE:
            continue
        with open(path, encoding="utf-8", errors="replace") as handle:
            text = normalise(handle.read())
        if text:
            found.append((name, text))
    return found


def read(path):
    with open(os.path.join(ROOT, path), encoding="utf-8") as handle:
        return normalise(handle.read())


