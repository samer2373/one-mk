#!/usr/bin/env python3
"""Writes css/fonts-file.css: the same @font-face rules as site.css with the
fonts inlined as data: URIs. Chrome refuses web fonts from file:// (each file
is its own origin), so the page loads this file only when opened from disk.
    python3 -I site/tools/inline-fonts.py site"""
import base64, sys
from pathlib import Path
root = Path(sys.argv[1])
faces = [("Inter", 400, "Inter-Regular"), ("Inter", 500, "Inter-Medium"), ("Inter", 600, "Inter-SemiBold"),
         ("JetBrains Mono", 400, "JetBrainsMono-Regular"), ("JetBrains Mono", 500, "JetBrainsMono-Medium"), ("Unbounded", 700, "Unbounded-Bold")]
out = ["/* Generated by tools/inline-fonts.py for file:// only; see site.css for the real rules. */"]
for fam, w, f in faces:
    b = base64.b64encode((root / "assets/fonts" / f"{f}.woff2").read_bytes()).decode()
    out.append(f'@font-face{{font-family:"{fam}";src:url(data:font/woff2;base64,{b}) format("woff2");font-weight:{w};font-display:swap}}')
(root / "css/fonts-file.css").write_text("\n".join(out) + "\n")
print("css/fonts-file.css", len("\n".join(out)))
