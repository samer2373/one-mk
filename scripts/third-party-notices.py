    out.append("")
    out.append(rule)
    out.append("LICENCE TEXTS AND NOTICES SHIPPED WITH THE CRATES")
    out.append(rule)
    for text, users in sorted(texts.items(), key=lambda item: item[1][0]):
        out.append("")
        out.append("-" * 78)
        out.append("Applies to:")
        out.extend(f"  {user}" for user in users)
        out.append("-" * 78)
        out.append("")
        out.append(text)
    if without_files:
        out.append("")
        out.append(rule)
        out.append("CRATES THAT SHIP NO LICENCE FILE")
        out.append(rule)
        out.append("")
        out.append("These crates name their licence only in their metadata. Their copyright")
        out.append("holders are the authors listed; the standard texts of their licences")
        out.append("are below (MIT and Apache-2.0 as in LICENSE-MIT and LICENSE-APACHE).")
        out.append("")
        for package in without_files:
            authors = ", ".join(package.get("authors") or []) or f"the {package['name']} authors"
            out.append(f"  {package['name']} {package['version']}: {package.get('license')}; copyright {authors}")
    out.append("")
    out.append(rule)
    out.append("STANDARD LICENCE TEXTS")
    out.append(rule)
    out.append("")
    out.append("-" * 78)
    out.append("MIT License (template; each component's copyright line is given above)")
    out.append("-" * 78)
    out.append("")
    out.append(re.sub(r"^Copyright.*$", "Copyright (c) <the component's copyright holders>", read("LICENSE-MIT"), count=1, flags=re.MULTILINE))
