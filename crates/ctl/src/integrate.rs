//! "Send to <computer>" entries in the file manager.
//!
//! Every entry runs `one-mk send --notify-errors --to <id> -- <files>`. The
//! computer is named by its fingerprint (hex), never by its name, so no
//! name chosen by another computer ever reaches a command line; names only
//! appear in menu labels and file names, cleaned first.
//!
//! - Linux: a script in the Nautilus (and Nemo) scripts folder, and one
//!   KDE service menu file for Dolphin. A file manager is only touched if
//!   its program is installed or its folder is already there.
//! - Windows: a `.cmd` per entry in the SendTo folder.
//! - macOS: a Quick Action (`.workflow` bundle, written as plain files) in
//!   `~/Library/Services`.
//!
//! Everything this module writes carries a marker, and only files with the
//! marker are replaced or removed, so a user's own scripts are never
//! touched: a file (or symlink) that is already where an entry would go and
//! does not carry the marker is left alone, and the entry is reported as
//! skipped. [`install`] and [`refresh`] (called when a computer is paired
//! or forgotten) rewrite the whole set; [`remove`] deletes it.

use anyhow::{Context, Result, bail};
use std::path::{Path, PathBuf};

/// First text in every generated file; what decides that a file is ours.
const MARKER: &str = "one-mk: generated by `one-mk integrate`";

/// A paired computer, as the menu needs it.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Computer {
    /// Fingerprint, lower-case hex.
    pub id: String,
    /// As the other computer calls itself; untrusted text.
    pub name: String,
}

impl Computer {
    /// `None` if `id` is not hex: it is going into a command line.
    pub fn new(id: &str, name: &str) -> Option<Self> {
        (id.len() >= 4 && id.bytes().all(|b| b.is_ascii_hexdigit()))
            .then(|| Self { id: id.to_ascii_lowercase(), name: name.to_owned() })
    }
}

/// What the entries run.
pub struct Setup {
    pub exe: PathBuf,
    /// `--home`, if the user chose a settings folder.
    pub home: Option<PathBuf>,
    pub computers: Vec<Computer>,
}

impl Setup {
    /// Refuses what must not be copied into a generated file: line breaks
    /// and NUL in a path would start new lines (directives) in the Dolphin
    /// menu, and no path of ours has any.
    fn check(&self) -> Result<()> {
        crate::install::check_plain("the program's path", &self.exe)?;
        match &self.home {
            Some(h) => crate::install::check_plain("the settings folder's path", h),
            None => Ok(()),
        }
    }
}

/// One menu entry.
#[derive(Clone, Debug, PartialEq, Eq)]
struct Item {
    /// Menu text, also the file name (without extension), safe for both.
    label: String,
    /// The computer's id; `None` leaves the choice to `one-mk send`.
    to: Option<String>,
}

/// The entries for these computers: with one computer a single "Send to
/// <name>"; with none a generic "Send with one-mk" (which says why it
/// cannot); with several, one per computer and a generic one that takes
/// the first.
fn items(computers: &[Computer]) -> Vec<Item> {
    let named = |c: &Computer, others: &[Computer]| {
        let mut label = format!("Send to {}", file_safe(&one_mk_proto::sanitize_name(&c.name)));
        // Two computers with one name: tell them apart by id.
        if others.iter().any(|o| o.id != c.id && format!("Send to {}", file_safe(&one_mk_proto::sanitize_name(&o.name))) == label) {
            label += &format!(" ({})", &c.id[..4]);
        }
        Item { label, to: Some(c.id.clone()) }
    };
    match computers {
        [] => vec![Item { label: "Send with one-mk".into(), to: None }],
        [one] => vec![named(one, computers)],
        many => {
            let mut v: Vec<Item> = many.iter().map(|c| named(c, many)).collect();
            v.push(Item { label: "Send with one-mk".into(), to: Some(many[0].id.clone()) });
            v
        }
    }
}

/// Safe as a file name on every system: no separators or characters
/// Windows rejects, no trailing dot or space, bounded.
fn file_safe(s: &str) -> String {
    let s: String = s.chars().map(|c| if matches!(c, '/' | '\\' | ':' | '*' | '?' | '"' | '<' | '>' | '|') { '_' } else { c }).collect();
    s.trim_end_matches(['.', ' ']).chars().take(80).collect()
}

/// `'...'` for `sh`.
fn sh_quote(s: &str) -> String {
    format!("'{}'", s.replace('\'', r"'\''"))
}

/// The `one-mk ... send ... --` part, as `sh` words, for `items`.
fn sh_command(setup: &Setup, item: &Item) -> String {
    let mut c = sh_quote(&setup.exe.display().to_string());
    if let Some(h) = &setup.home {
        c += &format!(" --home {}", sh_quote(&h.display().to_string()));
    }
    c += " send --notify-errors";
    if let Some(id) = &item.to {
        c += &format!(" --to {}", sh_quote(id));
    }
    c + " --"
}

/// A Nautilus or Nemo script. The files come as arguments; `--` first so a
/// file called `-rf` is a file.
fn shell_script(setup: &Setup, item: &Item) -> String {
    format!(
        "#!/bin/sh\n# {MARKER}\n# It is rewritten when a computer is paired or forgotten, and removed by `one-mk uninstall`.\n\
         [ \"$#\" -gt 0 ] || exit 0\n\
         exec {} \"$@\"\n",
        sh_command(setup, item)
    )
}

/// One word of a desktop-entry `Exec=` line, in double quotes where needed
/// (and with the backslashes doubled that the string rules ask for).
fn exec_word(w: &str) -> String {
    if w.chars().all(|c| c.is_ascii_alphanumeric() || matches!(c, '-' | '_' | '.' | '/' | '+' | ',' | ':' | '=')) {
        return w.to_owned();
    }
    let mut out = String::from("\"");
    for c in w.chars() {
        match c {
            '\\' => out.push_str(r"\\\\"),
            '"' | '`' | '$' => {
                out.push_str(r"\\");
                out.push(c);
            }
            '%' => out.push_str("%%"),
            _ => out.push(c),
        }
    }
    out + "\""
}

/// A desktop-entry text value: the escapes the specification gives for a
/// backslash and the three control characters it allows.
fn desktop_value(s: &str) -> String {
    s.replace('\\', r"\\").replace('\n', r"\n").replace('\r', r"\r").replace('\t', r"\t")
}

/// Dolphin's menu: one file, one action per entry (under a submenu when
/// there are several).
fn kde_service_menu(setup: &Setup, entries: &[Item]) -> String {
    let ids: String = (0..entries.len()).map(|i| format!("onemk{i};")).collect();
    let mut out = format!(
        "[Desktop Entry]\n# {MARKER}\nType=Service\nName=Send with one-mk\nMimeType=application/octet-stream;inode/directory;\n\
         X-KDE-ServiceTypes=KonqPopupMenu/Plugin\nActions={ids}\nX-KDE-Priority=TopLevel\n"
    );
    if entries.len() > 1 {
        out += "X-KDE-Submenu=Send with one-mk\n";
    }
    for (i, item) in entries.iter().enumerate() {
        let mut words = vec![setup.exe.display().to_string()];
        if let Some(h) = &setup.home {
            words.extend(["--home".to_owned(), h.display().to_string()]);
        }
        words.extend(["send".to_owned(), "--notify-errors".to_owned()]);
        if let Some(id) = &item.to {
            words.extend(["--to".to_owned(), id.clone()]);
        }
        words.push("--".to_owned());
        let exec: Vec<String> = words.iter().map(|w| exec_word(w)).collect();
        out += &format!(
            "\n[Desktop Action onemk{i}]\nName={}\nIcon=document-send\nExec={} %F\n",
            desktop_value(&item.label),
            exec.join(" ")
        );
    }
    out
}

/// A SendTo `.cmd`: the window stays open (on `pause`) if sending failed,
/// since Windows has no notification from one-mk yet.
fn windows_cmd(setup: &Setup, item: &Item) -> String {
    let q = |s: &str| format!("\"{}\"", s.replace('%', "%%"));
    let mut c = q(&setup.exe.display().to_string());
    if let Some(h) = &setup.home {
        c += &format!(" --home {}", q(&h.display().to_string()));
    }
    c += " send --notify-errors";
    if let Some(id) = &item.to {
        c += &format!(" --to {id}");
    }
    format!("@echo off\r\nREM {MARKER}\r\n{c} -- %*\r\nif errorlevel 1 pause\r\n")
}

fn xml_escape(s: &str) -> String {
    s.replace('&', "&amp;").replace('<', "&lt;").replace('>', "&gt;").replace('"', "&quot;")
}

/// A stable pseudo-UUID from the label (Automator wants UUIDs, nothing
/// checks that they are random).
fn uuid(label: &str, salt: u8) -> String {
    let mut h: u64 = 0xcbf29ce484222325 ^ u64::from(salt);
    let mut next = || {
        for b in label.bytes().chain([salt]) {
            h = (h ^ u64::from(b)).wrapping_mul(0x100000001b3);
        }
        h
    };
    let (a, b) = (next(), next());
    format!("{:08X}-{:04X}-4{:03X}-8{:03X}-{:012X}", a >> 32, (a >> 16) & 0xffff, a & 0xfff, (b >> 52) & 0xfff, b & 0xffff_ffff_ffff)
}

