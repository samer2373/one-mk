    out.append("This file is generated by scripts/third-party-notices.py from Cargo.lock;")
    out.append("do not edit it by hand.")
    out.append("")
    out.append(rule)
    out.append("NON-CRATE MATERIAL BUILT INTO ONEMK")
    out.append(rule)
