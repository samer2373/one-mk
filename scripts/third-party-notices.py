    out.append("  Copyright 2020 The JetBrains Mono Project Authors (https://github.com/JetBrains/JetBrainsMono)")
    out.append("  Licence: SIL Open Font License 1.1 (full text at the end of this file)")
    out.append("")
    out.append("Unbounded font (embedded in one-mk-app)")
    out.append("  Copyright 2022 The Unbounded Project Authors (https://github.com/googlefonts/unbounded)")
    out.append("  Licence: SIL Open Font License 1.1 (full text at the end of this file)")
    out.append("")
    out.append("3D mouse model shown in the window")
    out.append("  \"Logitech G502 x lightspeed\" by Okopchi")
    out.append("  (https://sketchfab.com/3d-models/logitech-g502-x-lightspeed-cda7107cc1444b4788d747f0361f7d40),")
    out.append("  licensed under CC BY 4.0 (https://creativecommons.org/licenses/by/4.0/).")
    out.append("  Changed: logo and feet left out, normals smoothed, shell split into its")
    out.append("  buttons and recoloured. Logitech and G502 are trademarks of their owner;")
    out.append("  oneMK is not affiliated with or endorsed by Logitech.")
    out.append("")
    out.append("Bigfoot Technology logo (embedded in one-mk-app, Settings > General > About)")
    out.append("  The mark of Bigfoot Technology (https://bigfootjo.com/), who make oneMK.")
    out.append("  It belongs to Bigfoot Technology and is not covered by oneMK's licence;")
    out.append("  see docs/brand/bigfoot/README.md.")
    out.append("")
    out.append(rule)
    out.append(f"RUST CRATES ({len(packages)})")
    out.append(rule)
    out.append("")
    texts = {}
    without_files = []
    for package in packages:
        source = package.get("repository") or f"https://crates.io/crates/{package['name']}"
        out.append(f"{package['name']} {package['version']}")
        out.append(f"  Licence: {package.get('license') or package.get('license_file') or 'see its licence file'}")
        out.append(f"  Source:  {source}")
        files = licence_files(package)
